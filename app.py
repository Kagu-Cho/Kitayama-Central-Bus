def collect_grouped_buses(sources: dict, now: datetime) -> dict[str, list[dict]]:
    """重複排除後、現在以降の到着予定順で方面別に抽出。"""
    grouped = {"kuzuha": [], "nagao": [], "makino": []}
    unique = {}
    for src in SOURCE_CONFIG:
        data = sources[src["id"]]
        if not data["ok"] or not data["updated"]:
            continue
        if (now - data["updated"]).total_seconds() > STALE_AFTER:
            # 古いキャッシュを無期限には表示しない
            continue
        for bus in data["buses"]:
            group = classify_bus(bus, src["group"], src.get("routes"))
            if not group:
                continue
            signature = (group, bus["route_id"], bus["scheduled_time"], bus["source_destination"])
            old = unique.get(signature)
            # 同じ便が複数URLに出たら見込み時刻があるデータを優先。
            if old is None or (bus["estimated"] and not old["estimated"]):
                unique[signature] = bus

    current_minutes = now.hour * 60 + now.minute
    for (group, _, _, _), bus in unique.items():
        distance = (_minutes(bus["time"]) - current_minutes) % (24 * 60)
        # 過ぎた時刻が「翌日扱い」になって誤表示されないようにする。
        if distance > 9 * 60:
            continue
        grouped[group].append((distance, _minutes(bus["scheduled_time"]), make_entry(bus)))
    for group in grouped:
        grouped[group].sort(key=lambda row: (row[0], row[1]))
        grouped[group] = [item[2] for item in grouped[group]][:2]
    return grouped


