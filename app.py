ROUTE_PATTERN = re.compile(r"系統\s*[:：]\s*[\[［【]\s*([^\]］】]+)\s*[\]］】]")
TIME_PATTERN = r"(?:[01]?\d|2[0-3]):[0-5]\d"
SCHEDULED_PATTERN = re.compile(r"定刻\s*[:：]?\s*(" + TIME_PATTERN + r")")
ESTIMATED_PATTERN = re.compile(r"(" + TIME_PATTERN + r")\s*(?:到着予定|発車予定|到着見込|発車見込)")
DELAY_PATTERN = re.compile(r"(?:約\s*)?(\d{1,3})\s*分\s*遅れ")


def norm_route(text: str) -> str:
    return html.unescape(text).strip().replace(" ", "").replace("　", "").upper()


class BusCardParser(HTMLParser):
    """HTMLの接近バス一覧 <dl><dd>1件...</dd></dl> から各便を抽出。

    ページ下部には同内容の詳細ポップアップが別途存在するため、
    実体の dd だけを対象として2重取り込みを防ぎます。
    """
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.cards = []
        self._in_dd = False
        self._buffer = []
        self._inside_script = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self._inside_script += 1
            return
        if self._inside_script:
            return
        if tag == "dd":
            self._in_dd = True
            self._buffer = []
        elif self._in_dd and tag in ("li", "p", "br", "div", "ul"):
            self._buffer.append("\n")

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self._inside_script = max(0, self._inside_script - 1)
        if self._inside_script:
            return
        if self._in_dd and tag == "dd":
            self.cards.append("".join(self._buffer))
            self._in_dd = False
            self._buffer = []
        elif self._in_dd and tag in ("li", "p", "br"):
            self._buffer.append("\n")

    def handle_data(self, data):
        if self._in_dd and not self._inside_script:
            self._buffer.append(data)


def first_label(block: str, name: str) -> str:
    """行ごとにラベルが分離された表示にも対応。"""
    m = re.search(r"(?m)^\s*" + re.escape(name) + r"\s*[:：]\s*([^\n]*)", block)
    return " ".join(m.group(1).split()) if m else ""


def delay_from_times(actual: str, scheduled: str) -> int:
    a_h, a_m = map(int, actual.split(":"))
    s_h, s_m = map(int, scheduled.split(":"))
    delta = a_h * 60 + a_m - (s_h * 60 + s_m)
    if delta < -720:
        delta += 1440
    if delta > 720:
        delta -= 1440
    return max(0, delta)


def parse_bus_cards(page_html: str) -> list[dict]:
    """系統・行先・経由地・到着見込み・定刻・遅れを構造単位で取得する。"""
    parser = BusCardParser()
    parser.feed(page_html)
    result = []
    for raw in parser.cards:
        block = "\n".join(" ".join(line.split()) for line in raw.splitlines() if line.strip())
        route_match = ROUTE_PATTERN.search(block)
        scheduled_match = SCHEDULED_PATTERN.search(block)
        if not route_match or not scheduled_match:
            continue
        if "到着済" in block or "運休" in block or "発車済" in block:
            continue
        route_id = norm_route(route_match.group(1))
        dest = first_label(block, "行先")
        via = first_label(block, "経由")
        if not dest:
            continue
        scheduled = scheduled_match.group(1)
        estimate_match = ESTIMATED_PATTERN.search(block)
        # 「未受信」では元の定刻を表示し、遅延情報は推定しない。
        estimated = bool(estimate_match) and "未受信" not in block
        departure = estimate_match.group(1) if estimated else scheduled
        delay_match = DELAY_PATTERN.search(block)
        delay_minutes = delay_from_times(departure, scheduled) if estimated else 0
        if estimated and delay_match:
            delay_minutes = max(delay_minutes, int(delay_match.group(1)))
        result.append({
            "route_id": route_id,
            "source_destination": dest,
            "source_via": via if via != "---" else "",
            "scheduled_time": scheduled,
            "time": departure,
            "estimated": estimated,
            "delay_minutes": delay_minutes,
        })
    return result


def build_params(cfg: dict, now: datetime | None = None) -> dict:
    """古いURLのdtを使い続けないため、ローカル現在時刻で再構成。"""
    current = now or japan_now()
    result = dict(COMMON_PARAMS)
    result.update({
        "dt": current.strftime("%Y%m%d%H%M"),
        "dgmpl": cfg["dgmpl"],
        "p": cfg["p"],
    })
    if "err" in cfg:
        result["err"] = cfg["err"]
    return result


def fetch_source(cfg: dict) -> None:
    try:
        resp = requests.get(
            BASE_URL + cfg["path"],
            params=build_params(cfg),
            headers={
                "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/131.0.0.0 Safari/537.36",
                "Accept-Language": "ja,en-US;q=0.9",
                "Referer": "https://busnavi.keihanbus.jp/pc/",
            },
            timeout=HTTP_TIMEOUT,
        )
        resp.raise_for_status()
        # 京阪バスPC版はUTF-8。推測に失敗した場合のみ検出値を利用。
        resp.encoding = resp.apparent_encoding or "utf-8"
        cards = parse_bus_cards(resp.text)
        if not cards:
            # ページは正常でも対象便がゼロ件のときがあり得る。
            # タイトルだけの検索トップ等へ転送された場合は更新成功とみなさない。
            if "接近バス一覧" not in resp.text:
                logging.warning("%s: 接近情報ページを取得できません（検索トップへの転送等）", cfg["id"])
                return
            after_list = resp.text.split("接近バス一覧", 1)[1]
            if "系統：" in after_list and "定刻" in after_list:
                logging.warning("%s: 接近情報は存在しますが、HTML構造を解析できません", cfg["id"])
                return
        with cache_lock:
            source_cache[cfg["id"]] = {"buses": cards, "updated": japan_now(), "ok": True}
        logging.info("%s: %d件取得", cfg["id"], len(cards))
    except (requests.RequestException, UnicodeError, ValueError) as exc:
        logging.warning("%s: 取得失敗: %s", cfg["id"], exc)


def update_loop() -> None:
    with ThreadPoolExecutor(max_workers=len(SOURCE_CONFIG)) as executor:
        while True:
            list(executor.map(fetch_source, SOURCE_CONFIG))
            time.sleep(FETCH_INTERVAL)


def classify_bus(bus: dict, source_group: str, allowed_routes=None) -> str | None:
    # 大2系統は専用ページからのみ、一般系統は従来ページからのみ採用。
    if allowed_routes is not None and bus["route_id"] not in allowed_routes:
        return None
    rule = ROUTE_RULES.get(bus["route_id"])
    if not rule:
        return None
    group = rule["group"]
    if source_group != ("kuzuha" if group == "kuzuha" else "south"):
        return None
    # 同じ番号でも逆方向・別の行先の便が存在するため、行先も照合。
    destination = bus["source_destination"].replace("ゆき", "行").replace(" ", "")
    if not any(keyword in destination for keyword in rule["match"]):
        return None
    # 直通は長尾行の直通便に限る。通常の長尾駅行きと区別する。
    if bus["route_id"] == "直通" and "長尾駅" not in destination:
        return None
    return group


def _minutes(time_string: str) -> int:
    hour, minute = map(int, time_string.split(":"))
    return hour * 60 + minute


def make_entry(bus: dict) -> dict:
    rid = bus["route_id"]
    rule = ROUTE_RULES[rid]
    via = VIA_BY_ROUTE.get(rid, bus["source_via"])
    stop = STOP_BY_ROUTE.get(rid, "")
    return {
        "route": f"[{rid}]", "route_id": rid,
        "destination": rule["destination"],
        "via": via,
        "time": bus["time"],
        "scheduled_time": bus["scheduled_time"],
        "delay": f"{bus['delay_minutes']}分" if bus["delay_minutes"] else "",
        "estimated": bus["estimated"],
        "stop_color": stop, "stop_label": STOP_LABELS.get(stop, ""),
        "available": True,
    }


