def get_board() -> dict:
    now = japan_now()
    with cache_lock:
        local = {key: {"buses": list(s["buses"]), "updated": s["updated"], "ok": s["ok"]} for key, s in source_cache.items()}
    if DEMO_MODE:
        local = {key: {"buses": [], "updated": now, "ok": True} for key in local}
        for sid, bus in DEMO_CARDS:
            local[sid]["buses"].append(bus)
        # デモの時刻は12時台のため、現在時刻によらず並び順が確認できるようにする
        now = now.replace(hour=12, minute=20)
        for state in local.values():
            state["updated"] = now
    grouped = collect_grouped_buses(local, now)
    items = []
    for cfg in BUS_CONFIG:
        group = "kuzuha" if cfg["group"] == "kuzuha" else "nagao" if cfg["key"] == "長尾方面" else "makino"
        source_ids = [s["id"] for s in SOURCE_CONFIG if s["group"] == cfg["group"]]
        valid = [local[sid]["updated"] for sid in source_ids if local[sid]["updated"] and (now - local[sid]["updated"]).total_seconds() <= STALE_AFTER]
        is_loaded = bool(valid)
        rows = grouped[group]
        # 0便：先発に終了案内、次発行は完全空欄。
        # 1便：先発は通常表示、次発行は完全空欄。
        # 未取得・通信障害の場合は終了と判断せず「取得中…」を表示。
        first = rows[0] if rows else empty_entry("本日の運行は終了しました" if is_loaded else "取得中…")
        second = rows[1] if len(rows) > 1 else empty_entry()
        items.append({
            "key": cfg["key"], "destination_label": cfg["destination"], "color": cfg["color"],
            "first": first, "next": second,
            "updated": max(valid).strftime("%H:%M:%S") if valid else "未取得",
            "stale": not is_loaded,
        })
    return {"items": items, "demo": DEMO_MODE, "server_time": japan_now().strftime("%H:%M:%S")}


